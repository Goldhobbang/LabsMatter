#!/usr/bin/env python3
"""Generate `crates/realmatter-tpt/src/element_defaults.rs`.

The reference `Element` table assigns `DefaultProperties` (life / ctype / tmp /
tmp2 / tmp3 / tmp4 / vx / vy / temp). `temp` is already carried by
`ElementDef::default_temp`; this file covers the remaining fields so a freshly
created particle starts with the same state as the reference.

Source: docs/tpt-parity/data/tpt-reference.json (pinned TPT commit).
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, "docs", "tpt-parity", "data", "tpt-reference.json")
OUT = os.path.join(ROOT, "crates", "realmatter-tpt", "src", "element_defaults.rs")

FIELDS = ["life", "ctype", "tmp", "tmp2", "tmp3", "tmp4", "vx", "vy"]


def main():
    data = json.load(open(DATA, encoding="utf-8"))
    entries = []
    for e in data["elements"]:
        if e.get("disabled_slot"):
            continue
        props = e.get("default_properties") or {}
        vals = {k: props[k] for k in FIELDS if props.get(k) is not None}
        if not vals:
            continue
        parts = []
        for k in FIELDS:
            if k not in vals:
                continue
            v = vals[k]
            if isinstance(v, float):
                parts.append(f"{k}: Some({repr(v)}f32)")
            elif k == "ctype" and v > 0:
                parts.append(f"{k}: Some(0x{v:X}u32 as i32)")
            else:
                parts.append(f"{k}: Some({int(v)})")
        entries.append((e["id"], e.get("name") or e.get("slot_name") or "", ", ".join(parts)))

    lines = []
    lines.append("// @generated by tools/tpt-inventory/gen_element_defaults.py — do not edit by hand.")
    lines.append("//")
    lines.append("// Reference `DefaultProperties` other than `temp` (carried by")
    lines.append("// `ElementDef::default_temp`). Applied when a particle is created.")
    lines.append("")
    lines.append("/// Subset of the reference `DefaultProperties` that is not the default")
    lines.append("/// temperature. `None` means \"leave the engine default\".")
    lines.append("#[derive(Clone, Copy, Debug, Default)]")
    lines.append("pub struct DefaultProps {")
    for k in FIELDS:
        ty = "f32" if k in ("vx", "vy") else "i32"
        lines.append(f"    pub {k}: Option<{ty}>,")
    lines.append("}")
    lines.append("")
    lines.append("/// Reference default properties for element `t`, or `None`.")
    lines.append("pub fn defaults(t: u16) -> Option<DefaultProps> {")
    lines.append("    Some(match t {")
    for eid, name, body in entries:
        lines.append(f"        {eid} => DefaultProps {{ {body}, ..DefaultProps::default() }}, // {name}")
    lines.append("        _ => return None,")
    lines.append("    })")
    lines.append("}")
    lines.append("")
    lines.append(f"/// Number of elements with non-temperature defaults: {len(entries)}.")
    lines.append(f"pub const DEFAULT_COUNT: usize = {len(entries)};")
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} ({len(entries)} entries)")


if __name__ == "__main__":
    main()
