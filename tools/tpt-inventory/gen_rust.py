#!/usr/bin/env python3
"""Generate the Rust element table and the JS palette data from the vendored
TPT reference JSON.

Outputs:
  crates/realmatter-tpt/src/elements_generated.rs
  web/src/adapters/tpt-elements.generated.js
"""

import json
import os
import sys

PROPS = [
    ("TYPE_PART", 0x00000001),
    ("TYPE_LIQUID", 0x00000002),
    ("TYPE_SOLID", 0x00000004),
    ("TYPE_GAS", 0x00000008),
    ("TYPE_ENERGY", 0x00000010),
    ("PROP_CONDUCTS", 0x00000020),
    ("PROP_PHOTPASS", 0x00000040),
    ("PROP_NEUTPENETRATE", 0x00000080),
    ("PROP_NEUTABSORB", 0x00000100),
    ("PROP_NEUTPASS", 0x00000200),
    ("PROP_DEADLY", 0x00000400),
    ("PROP_HOT_GLOW", 0x00000800),
    ("PROP_LIFE", 0x00001000),
    ("PROP_RADIOACTIVE", 0x00002000),
    ("PROP_LIFE_DEC", 0x00004000),
    ("PROP_LIFE_KILL", 0x00008000),
    ("PROP_LIFE_KILL_DEC", 0x00010000),
    ("PROP_SPARKSETTLE", 0x00020000),
    ("PROP_NOAMBHEAT", 0x00040000),
    ("PROP_NOCTYPEDRAW", 0x00100000),
]

SECTION_NAMES = [
    "Walls",
    "Electronics",
    "Powered Materials",
    "Sensors",
    "Force",
    "Explosives",
    "Gases",
    "Liquids",
    "Powders",
    "Solids",
    "Radioactive",
    "Special",
    "Game Of Life",
    "Tools",
    "Favorites",
    "Decoration tools",
]


def f(v):
    """Rust float literal."""
    if v is None:
        return "0.0"
    if isinstance(v, int):
        return f"{v}.0"
    s = repr(float(v))
    if "e" in s or "E" in s:
        s = f"{v:.9f}"
    if s in ("inf", "-inf", "nan"):
        s = "f32::INFINITY" if s == "inf" else ("f32::NEG_INFINITY" if s == "-inf" else "f32::NAN")
        return s
    return s


def rust_str(s):
    if s is None:
        return '""'
    return json.dumps(s, ensure_ascii=True).replace("\\u", "\\u{")


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    data = json.load(open(os.path.join(root, "docs", "tpt-parity", "data", "tpt-reference.json"), encoding="utf-8"))
    els = data["elements"]
    pt_num = data["pt_num"]

    lines = []
    w = lines.append
    w("// @generated by tools/tpt-inventory/gen_rust.py — do not edit by hand.")
    w("//")
    w("// Source: The-Powder-Toy @ 2b7221a46d378589b4de7683f16d3ebc92be6bd9")
    w("//   src/simulation/elements/*.cpp, src/simulation/elements/meson.build,")
    w("//   src/simulation/ElementDefs.h, src/simulation/MenuSection.h")
    w("//")
    w("// Numeric IDs are the reference PT_* IDs so that TPT saves can be mapped.")
    w("")
    w("use crate::element::{ElementDef, EMPTY_ELEMENT};")
    w("")
    w(f"pub const PT_NUM: usize = {pt_num};")
    w("")
    w("/// Element id constants, mirroring `PT_*` in the reference.")
    w("pub mod pt {")
    for e in els:
        if e.get("disabled_slot"):
            continue
        name = e["slot_name"]
        if name == "NONE":
            continue
        w(f"    pub const {name}: u16 = {e['id']};")
    w("    pub const NONE: u16 = 0;")
    w("}")
    w("")
    w("/// Property flag bits, mirroring `TYPE_*` / `PROP_*` in ElementDefs.h.")
    w("pub mod props {")
    for name, bit in PROPS:
        w(f"    pub const {name}: u32 = 0x{bit:08X};")
    w("    pub const STATE_FLAGS: u32 = 0x0000001F;")
    w("}")
    w("")
    w("pub const SECTION_NAMES: [&str; 16] = [")
    for n in SECTION_NAMES:
        w(f"    {rust_str(n)},")
    w("];")
    w("")
    w("#[rustfmt::skip]")
    w(f"pub static ELEMENTS: [ElementDef; PT_NUM] = [")
    by_id = {e["id"]: e for e in els}
    for i in range(pt_num):
        e = by_id.get(i)
        if e is None or e.get("disabled_slot"):
            w("    EMPTY_ELEMENT,")
            continue
        dp = e.get("default_properties") or {}
        temp = dp.get("temp")
        if temp is None:
            temp = 293.15
        w("    ElementDef {")
        w(f"        id: {e['id']},")
        w(f"        abbr: {rust_str(e['slot_name'])},")
        w(f"        name: {rust_str(e.get('name'))},")
        w(f"        identifier: {rust_str(e.get('identifier'))},")
        w(f"        description: {rust_str(e.get('description'))},")
        w(f"        colour: 0x{(e.get('colour') or 0xFF00FF):06X},")
        w(f"        menu_visible: {'true' if e.get('menu_visible') else 'false'},")
        w(f"        menu_section: {e.get('menu_section', 0)},")
        w(f"        enabled: {'true' if e.get('enabled') else 'false'},")
        w(f"        advection: {f(e['advection'])},")
        w(f"        air_drag: {f(e['airdrag'])},")
        w(f"        air_loss: {f(e['airloss'])},")
        w(f"        loss: {f(e['loss'])},")
        w(f"        collision: {f(e['collision'])},")
        w(f"        gravity: {f(e['gravity'])},")
        w(f"        newtonian_gravity: {f(e['newtonian_gravity'])},")
        w(f"        diffusion: {f(e['diffusion'])},")
        w(f"        hot_air: {f(e['hotair'])},")
        w(f"        falldown: {e['falldown']},")
        w(f"        flammable: {e['flammable']},")
        w(f"        explosive: {e['explosive']},")
        w(f"        meltable: {e['meltable']},")
        w(f"        hardness: {e['hardness']},")
        w(f"        photon_reflect: 0x{e['photon_reflect']:08X},")
        w(f"        weight: {e['weight']},")
        w(f"        heat_conduct: {e['heat_conduct']},")
        w(f"        heat_capacity: {f(e['heat_capacity'])},")
        w(f"        properties: 0x{e['properties']:08X},")
        w(f"        carries_type_in: 0x{e['carries_type_in']:08X},")
        w(f"        low_pressure: {f(e['low_pressure'])},")
        w(f"        low_pressure_transition: {e['low_pressure_transition']},")
        w(f"        high_pressure: {f(e['high_pressure'])},")
        w(f"        high_pressure_transition: {e['high_pressure_transition']},")
        w(f"        low_temperature: {f(e['low_temperature'])},")
        w(f"        low_temperature_transition: {e['low_temperature_transition']},")
        w(f"        high_temperature: {f(e['high_temperature'])},")
        w(f"        high_temperature_transition: {e['high_temperature_transition']},")
        w(f"        default_temp: {f(temp)},")
        w(f"        has_update: {'true' if 'update' in e.get('functions', []) else 'false'},")
        w(f"        has_graphics: {'true' if 'graphics' in e.get('functions', []) else 'false'},")
        w("    },")
    w("];")
    w("")

    out_rs = os.path.join(root, "crates", "realmatter-tpt", "src", "elements_generated.rs")
    os.makedirs(os.path.dirname(out_rs), exist_ok=True)

    # ---- walls + GoL rules ----------------------------------------------
    extra = []
    a = extra.append
    a("")
    a("/// Wall definition, mirroring `wall_type` (UI order from `LoadWalls`).")
    a("pub struct WallDef {")
    a("    pub id: u8,")
    a("    pub identifier: &'static str,")
    a("    pub name: &'static str,")
    a("    pub description: &'static str,")
    a("    pub colour: u32,")
    a("    pub eglow: u32,")
    a("    pub drawstyle: u8,")
    a("}")
    a("")
    a("pub static WALLS: [WallDef; %d] = [" % len(data["walls"]))
    for wl in data["walls"]:
        a(
            '    WallDef { id: %d, identifier: %s, name: %s, description: %s, colour: 0x%06X, eglow: 0x%06X, drawstyle: %d },'
            % (
                wl["id"],
                rust_str(wl["identifier"]),
                rust_str(wl["name"]),
                rust_str(wl["description"]),
                wl["colour"],
                wl["eglow"],
                wl["drawstyle"],
            )
        )
    a("];")
    a("")
    a("/// Built-in Game of Life rules, mirroring `builtinGol`.")
    a("pub struct GolRule {")
    a("    pub name: &'static str,")
    a("    /// bits 0..8 = stay-if-N neighbours, bits 9..17 = begin-if-N, bits 17..20 = states-2.")
    a("    pub ruleset: u32,")
    a("    pub states: u8,")
    a("    pub colour1: u32,")
    a("    pub colour2: u32,")
    a("    pub description: &'static str,")
    a("}")
    a("")
    a("pub static GOL_RULES: [GolRule; %d] = [" % len(data["gol_rules"]))
    for g in data["gol_rules"]:
        a(
            '    GolRule { name: %s, ruleset: 0x%05X, states: %d, colour1: 0x%06X, colour2: 0x%06X, description: %s },'
            % (
                rust_str(g["name"]),
                g["rule"],
                g["states"],
                g["colour1"],
                g["colour2"],
                rust_str(g["description"]),
            )
        )
    a("];")
    a("")
    lines.extend(extra)

    with open(out_rs, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote", out_rs, len(lines), "lines")

    # ---- JS palette data -------------------------------------------------
    js = []
    j = js.append
    j("// @generated by tools/tpt-inventory/gen_rust.py — do not edit by hand.")
    j("// Source: The-Powder-Toy @ 2b7221a46d378589b4de7683f16d3ebc92be6bd9")
    j("")
    j("export const PT_NUM = %d;" % pt_num)
    j("export const SECTIONS = [")
    for i, n in enumerate(SECTION_NAMES):
        j("  { id: %d, name: %s }," % (i, json.dumps(n)))
    j("];")
    j("export const PROP_FLAGS = {")
    for name, bit in PROPS:
        j("  %s: 0x%08X," % (name, bit))
    j("};")
    j("")
    j("export const ELEMENTS = [")
    for e in els:
        if e.get("disabled_slot"):
            continue
        dp = e.get("default_properties") or {}
        temp = dp.get("temp", 293.15)
        j(
            "  { id: %d, abbr: %s, name: %s, identifier: %s, desc: %s, colour: 0x%06X, "
            "section: %d, menu: %s, props: 0x%08X, weight: %d, falldown: %d, "
            "flammable: %d, heatConduct: %d, temp: %s, update: %s, graphics: %s },"
            % (
                e["id"],
                json.dumps(e["slot_name"]),
                json.dumps(e.get("name") or ""),
                json.dumps(e.get("identifier") or ""),
                json.dumps(e.get("description") or ""),
                (e.get("colour") or 0xFF00FF),
                e.get("menu_section", 0),
                "true" if e.get("menu_visible") else "false",
                e["properties"],
                e["weight"],
                e["falldown"],
                e["flammable"],
                e["heat_conduct"],
                json.dumps(temp),
                "true" if "update" in e.get("functions", []) else "false",
                "true" if "graphics" in e.get("functions", []) else "false",
            )
        )
    j("];")
    j("")
    out_js = os.path.join(root, "web", "src", "adapters", "tpt-elements.generated.js")
    os.makedirs(os.path.dirname(out_js), exist_ok=True)
    with open(out_js, "w", encoding="utf-8") as fh:
        fh.write("\n".join(js))
    print("wrote", out_js, len(js), "lines")


if __name__ == "__main__":
    sys.exit(main())
