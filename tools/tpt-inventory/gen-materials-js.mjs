// Generate web/src/tpt-materials.js from the source-derived TPT reference.
//
// Usage: node tools/tpt-inventory/gen-materials-js.mjs
//
// The JSON is produced by tools/tpt-inventory/gen_inventory.py from the pinned
// The Powder Toy commit. This script only reshapes it for the browser; it does
// not invent or remap any ids.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..");
const jsonPath = join(root, "docs", "tpt-parity", "data", "tpt-reference.json");
const outPath = join(root, "web", "src", "tpt-materials.js");

const SLUGS = {
  Walls: "walls",
  Electronics: "electronics",
  "Powered Materials": "powered",
  Sensors: "sensors",
  Force: "force",
  Explosives: "explosives",
  Gases: "gases",
  Liquids: "liquids",
  Powders: "powders",
  Solids: "solids",
  Radioactive: "radioactive",
  Special: "special",
  "Game Of Life": "gol",
  Tools: "tools",
  Favorites: "favorites",
  "Decoration tools": "decoration",
};

const SHORT = {
  walls: "WLL",
  electronics: "ELE",
  powered: "PWR",
  sensors: "SNS",
  force: "FRC",
  explosives: "EXP",
  gases: "GAS",
  liquids: "LIQ",
  powders: "PWD",
  solids: "SOL",
  radioactive: "RAD",
  special: "SPC",
  gol: "GOL",
  tools: "TOL",
  favorites: "FAV",
  decoration: "DEC",
};

const hex = (n) => "#" + (n & 0xffffff).toString(16).padStart(6, "0");
const esc = (s) => String(s || "").replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, " ");

const data = JSON.parse(await readFile(jsonPath, "utf8"));
const sectionById = new Map(data.sections.map((s) => [s.id, s]));

const sections = data.sections
  .map((s) => ({
    id: SLUGS[s.name] || `section-${s.id}`,
    label: s.name,
    short: SHORT[SLUGS[s.name]] || s.name.slice(0, 3).toUpperCase(),
    sectionId: s.id,
  }))
  .filter((s) => s.id && s.id !== "favorites" && s.id !== "decoration");

const materials = [];

// Elements: PT id space. Keep menu-visible, enabled entries.
for (const e of data.elements) {
  if (!e.enabled || !e.menu_visible) continue;
  const sec = sectionById.get(e.menu_section);
  const slug = sec ? SLUGS[sec.name] || `section-${sec.id}` : "special";
  materials.push({
    id: e.id,
    ptId: e.id,
    kind: "element",
    abbr: e.name,
    name: e.name,
    color: hex(e.colour),
    section: slug,
    menuSection: e.menu_section,
    menuVisible: true,
    enabled: true,
    weight: e.weight,
    desc: esc(e.description),
  });
}

// Walls: separate id space, offset so the palette can address them without
// colliding with element ids. `wallIdOf` recovers the engine wall id.
const WALL_ID_BASE = 1000;
for (const w of data.walls) {
  materials.push({
    id: WALL_ID_BASE + w.id,
    ptId: WALL_ID_BASE + w.id,
    wallId: w.id,
    kind: "wall",
    abbr: w.name.replace(/\s+/g, ""),
    name: w.name,
    color: hex(w.colour),
    section: "walls",
    menuVisible: true,
    enabled: true,
    weight: 0,
    desc: esc(w.description),
  });
}

materials.sort((a, b) => (a.kind === b.kind ? a.ptId - b.ptId : a.kind === "element" ? -1 : 1));

const lines = [];
lines.push("// AUTO-GENERATED by tools/tpt-inventory/gen-materials-js.mjs");
lines.push("// Source: docs/tpt-parity/data/tpt-reference.json (The Powder Toy");
lines.push("// 2b7221a46d378589b4de7683f16d3ebc92be6bd9). Do not edit by hand.");
lines.push("");
lines.push(`export const WALL_ID_BASE = ${WALL_ID_BASE};`);
lines.push("");
lines.push(`export const TPT_SECTIONS = ${JSON.stringify(sections, null, 0)};`);
lines.push("");
lines.push(`export const TPT_MATERIALS = [`);
for (const m of materials) {
  lines.push("  " + JSON.stringify(m) + ",");
}
lines.push("];");
lines.push("");
lines.push(`export const CATEGORIES = [
  { id: "all", label: "All", short: "ALL" },
  ...TPT_SECTIONS.map((s) => ({ id: s.id, label: s.label, short: s.short })),
];`);
lines.push("");
lines.push(`export const MATERIALS = TPT_MATERIALS;`);
lines.push("");
lines.push(`const BY_ID = new Map(TPT_MATERIALS.map((m) => [m.id, m]));`);
lines.push(`export function findTptMaterial(id) {`);
lines.push(`  return BY_ID.get(id) || { id: id | 0, abbr: "?", name: "Unknown", color: "#ff00ff", section: "special", desc: "" };`);
lines.push(`}`);
lines.push("");
lines.push(`export const findMaterial = findTptMaterial;`);
lines.push("");
lines.push(`export function searchTptMaterials(query, category) {`);
lines.push(`  const q = (query || "").trim().toLowerCase();`);
lines.push(`  return TPT_MATERIALS.filter((m) => {`);
lines.push(`    if (category && category !== "all" && m.section !== category) return false;`);
lines.push(`    if (!q) return true;`);
lines.push(`    return (`);
lines.push(`      m.name.toLowerCase().includes(q) ||`);
lines.push(`      m.abbr.toLowerCase().includes(q) ||`);
lines.push(`      (m.desc || "").toLowerCase().includes(q)`);
lines.push(`    );`);
lines.push(`  });`);
lines.push(`}`);
lines.push("");
lines.push(`export const searchMaterials = searchTptMaterials;`);
lines.push("");
lines.push(`export function isWallMaterial(id) { return (id | 0) >= WALL_ID_BASE && (id | 0) < WALL_ID_BASE + 64; }`);
lines.push(`export function wallIdOf(id) { return (id | 0) - WALL_ID_BASE; }`);
lines.push(`export function elementIdOf(id) { return id | 0; }`);
lines.push("");
lines.push(`// Convenience ids for the default brush.`);
lines.push(`export const DEFAULT_MATERIAL_ID = ${materials.find((m) => m.abbr === "SAND")?.id ?? 0};`);
lines.push(`export const DEFAULT_CATEGORY = "powders";`);
lines.push("");

await writeFile(outPath, lines.join("\n"));
console.log(`wrote ${outPath} (${materials.length} materials, ${sections.length} sections)`);
